-- КАР-точки — миграция 0012: бакет card-images становится приватным
--
-- Зачем: маршрут /storage/v1/object/public/card-images/… отдаёт файл вообще
-- без проверки RLS. Политика «read own images» из миграции 0009 закрыла только
-- листинг: кто угодно, узнав (или подобрав) путь вида {user_id}/{uuid}.jpg,
-- читал чужие картинки. Приватный бакет заставляет ходить через
-- /object/sign/… — а там уже работает та самая политика.
--
-- ⚠️ ПРИМЕНЯТЬ ТОЛЬКО ПОСЛЕ ВЫКАТКИ КЛИЕНТА С ПОДПИСАННЫМИ ССЫЛКАМИ
-- (js/data/image-url.ts + вызовы resolveImageUrl на всех экранах). Старый
-- клиент после этой миграции покажет вместо картинок «битые» изображения:
-- сохранённые в карточках ссылки останутся публичными и перестанут отвечать.
-- Откат: update storage.buckets set public = true where id = 'card-images';
--
-- Ссылки в самих карточках не переписываем сознательно: они стабильны, по ним
-- же удаляется файл, а подпись выдаётся на лету перед показом.
-- ============================================================

update storage.buckets set public = false where id = 'card-images';

insert into public.schema_meta (id, version)
values (1, 12)
on conflict (id) do update
  set version = greatest(public.schema_meta.version, excluded.version),
      updated_at = now();
